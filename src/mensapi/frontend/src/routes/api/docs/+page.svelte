<h1>Dokumentation</h1>
<p>Die Anwendung benutzt eine eigene Programmierschnittstelle, um das Menü darzustellen.
Die Schnittstelle heißt MensAPI und ist <a href="https://github.com/kawa800/MensAPI">unter Github zu finden</a>. 
</p>

<p>Sie finden die OpenAPI-Dokumentation der Schnittstelle unter <a href="https://mensapi.de/docs">mensapi.de/docs</a>. Etwa schreiben Sie in Ihre Browserleiste <a href="https://mensapi.de/docs">mensapi.de/week/?start=2026-10-06&end=2026-10-10</a>, um die Daten der Menüs zwischen dem 06.10 und 10.10.2026 zu filtern. </p>

<p>Ein Rasperry Pi aktualisiert die Daten jeden Sonntag. Diese stammen von der offiziellen <a href='https://mocca.stw-d.de/mocca.digitalsignage/3500/Speiseplan3500/Index.html'> Website des Studierendenwerks Düsseldorf </a>. </p>
